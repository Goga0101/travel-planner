// Builds src/TravelPlanner.API/catalog/world-airports.json from the Travelpayouts static data files (free, no key):
// every flightable airport with its city, country and continent. The API seeds these as departure airports and uses them
// for destinations outside the curated catalog. Travelpayouts has no continent field, so it is derived from the IANA
// time zones of each country's airports, with explicit overrides below.
//
// Usage: node scripts/fetch-world-airports.mjs

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = join(root, 'src/TravelPlanner.API/catalog/world-airports.json');
const DATA = 'https://api.travelpayouts.com/data/en';

const SOUTH_AMERICA = new Set(['AR', 'BO', 'BR', 'CL', 'CO', 'EC', 'FK', 'GF', 'GY', 'PE', 'PY', 'SR', 'UY', 'VE']);
const OVERRIDES = {
  // Transcontinental or ambiguous time zones, assigned to where travellers usually place them.
  GE: 'Europe', AM: 'Europe', AZ: 'Europe', CY: 'Europe', RU: 'Europe', TR: 'Europe', KZ: 'Asia',
  CV: 'Africa', MU: 'Africa', SC: 'Africa', RE: 'Africa', KM: 'Africa', YT: 'Africa', MG: 'Africa',
  MV: 'Asia', IO: 'Asia', CX: 'Oceania', CC: 'Oceania', BM: 'NorthAmerica', IS: 'Europe', US: 'NorthAmerica',
};

function continentOfZone(zone, countryCode) {
  const prefix = (zone ?? '').split('/')[0];
  switch (prefix) {
    case 'Europe': return 'Europe';
    case 'Asia': return 'Asia';
    case 'Africa': return 'Africa';
    case 'Australia':
    case 'Pacific': return 'Oceania';
    case 'America': return SOUTH_AMERICA.has(countryCode) ? 'SouthAmerica' : 'NorthAmerica';
    case 'Atlantic': return 'Europe';
    case 'Indian': return 'Africa';
    default: return null;
  }
}

async function load(name) {
  const res = await fetch(`${DATA}/${name}.json`);
  if (!res.ok) throw new Error(`${name}.json returned HTTP ${res.status}`);
  return res.json();
}

const [airports, cities, countries] = await Promise.all([load('airports'), load('cities'), load('countries')]);
const cityByCode = new Map(cities.map((c) => [c.code, c]));
const countryByCode = new Map(countries.map((c) => [c.code, c]));

const flightable = airports.filter(
  (a) => a.flightable && a.iata_type === 'airport' && /^[A-Z]{3}$/.test(a.code ?? '') && a.coordinates && a.country_code && countryByCode.has(a.country_code),
);

// Continent per country: majority of its airports' time zones, unless overridden.
const votes = new Map();
for (const a of flightable) {
  const c = continentOfZone(a.time_zone, a.country_code);
  if (!c) continue;
  const v = votes.get(a.country_code) ?? {};
  v[c] = (v[c] ?? 0) + 1;
  votes.set(a.country_code, v);
}
const continentOf = (cc) =>
  OVERRIDES[cc] ?? Object.entries(votes.get(cc) ?? {}).sort((x, y) => y[1] - x[1])[0]?.[0] ?? null;

const result = flightable
  .map((a) => {
    const city = cityByCode.get(a.city_code);
    const continent = continentOf(a.country_code);
    if (!continent) return null;
    return {
      iata: a.code,
      name: a.name_translations?.en || a.name,
      cityCode: a.city_code || a.code,
      city: city?.name_translations?.en || city?.name || a.name,
      countryCode: a.country_code,
      country: countryByCode.get(a.country_code).name_translations?.en || countryByCode.get(a.country_code).name,
      continent,
      latitude: Math.round(a.coordinates.lat * 1e5) / 1e5,
      longitude: Math.round(a.coordinates.lon * 1e5) / 1e5,
      cityLatitude: Math.round((city?.coordinates?.lat ?? a.coordinates.lat) * 1e5) / 1e5,
      cityLongitude: Math.round((city?.coordinates?.lon ?? a.coordinates.lon) * 1e5) / 1e5,
      timeZone: a.time_zone || city?.time_zone || null,
    };
  })
  .filter(Boolean)
  .sort((x, y) => x.iata.localeCompare(y.iata));

const doc = {
  $comment: 'Generated by scripts/fetch-world-airports.mjs from Travelpayouts static data (api.travelpayouts.com/data). Do not edit by hand.',
  generatedOn: new Date().toISOString().slice(0, 10),
  airports: result,
};
writeFileSync(outPath, JSON.stringify(doc) + '\n');
const perContinent = result.reduce((m, a) => ((m[a.continent] = (m[a.continent] ?? 0) + 1), m), {});
console.log(`Wrote ${result.length} airports to ${outPath}`, perContinent);

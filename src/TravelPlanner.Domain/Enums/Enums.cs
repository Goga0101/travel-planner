namespace TravelPlanner.Domain.Enums;

public enum TripSearchStatus
{
    Queued = 0,
    Running = 1,
    Completed = 2,
    CompletedNoMatch = 3,
    Failed = 4,
    Cancelled = 5
}

public enum DestinationMode
{
    Automatic = 0,
    Manual = 1
}

public enum DataMode
{
    Live = 0,
    Demo = 1
}

public enum PlanItemType
{
    Flight = 0,
    Accommodation = 1,
    Transfer = 2,
    Fee = 3,
    DailyExpenseEstimate = 4,
    Contingency = 5
}

public enum TransferDirection
{
    None = 0,
    AirportToAccommodation = 1,
    AccommodationToAirport = 2
}

/// <summary>How trustworthy a price or piece of information is.</summary>
public enum VerificationStatus
{
    /// <summary>Retrieved from the provider during this search and not yet expired.</summary>
    Live = 0,
    /// <summary>Provider-side cached price indication (e.g. prices other users found recently).</summary>
    Cached = 1,
    /// <summary>Calculated estimate (route-based, configured tariff, configured daily cost). Never a quote.</summary>
    Estimate = 2,
    /// <summary>Generated by the demo provider. Not real data.</summary>
    Demo = 3,
    /// <summary>No data could be obtained.</summary>
    Unavailable = 4,
    /// <summary>Curated catalog information (e.g. an official airport website) checked by the operator. Not a price.</summary>
    Verified = 5
}

public enum BudgetFitStatus
{
    WithinBudget = 0,
    /// <summary>Known costs fit, but at least one required cost category is missing.</summary>
    WithinBudgetIncomplete = 1,
    OverBudget = 2,
    Unknown = 3
}

